-- Function to check booking overlap
CREATE OR REPLACE FUNCTION check_booking_overlap(
    p_room_id UUID,
    p_start_date TIMESTAMP WITH TIME ZONE,
    p_end_date TIMESTAMP WITH TIME ZONE,
    p_exclude_booking_id UUID DEFAULT NULL
)
RETURNS BOOLEAN AS $$
DECLARE
    v_overlap_exists BOOLEAN;
BEGIN
    SELECT EXISTS (
        SELECT 1 
        FROM "Bookings" b
        WHERE b."RoomId" = p_room_id
          AND b."IsDeleted" = FALSE
          AND b."Status" IN ('Pending', 'Approved')
          AND b."Id" != COALESCE(p_exclude_booking_id, '00000000-0000-0000-0000-000000000000'::uuid)
          AND b."BookingStartDate" < p_end_date
          AND b."BookingEndDate" > p_start_date
    ) INTO v_overlap_exists;
    
    RETURN v_overlap_exists;
END;
$$ LANGUAGE plpgsql;

-- Function to get available time slots for a room on a specific date
CREATE OR REPLACE FUNCTION get_available_slots(
    p_room_id UUID,
    p_date DATE,
    p_slot_duration INTERVAL DEFAULT '1 hour'::interval
)
RETURNS TABLE(slot_start TIME, slot_end TIME) AS $$
DECLARE
    v_day_start TIMESTAMP WITH TIME ZONE;
    v_day_end TIMESTAMP WITH TIME ZONE;
    v_current_time TIMESTAMP WITH TIME ZONE;
BEGIN
    -- Set working hours (8:00 AM - 6:00 PM)
    v_day_start := p_date AT TIME ZONE 'UTC';
    v_day_end := (p_date + INTERVAL '1 day') AT TIME ZONE 'UTC';
    
    -- Working hours: 08:00 - 18:00
    v_day_start := v_day_start + INTERVAL '8 hours';
    v_day_end := v_day_end + INTERVAL '18 hours';
    
    -- Generate time slots
    v_current_time := v_day_start;
    
    WHILE v_current_time < v_day_end LOOP
        -- Check if this slot overlaps with any booking
        IF NOT check_booking_overlap(p_room_id, v_current_time, v_current_time + p_slot_duration) THEN
            RETURN QUERY SELECT 
                CAST(v_current_time AS TIME),
                CAST(v_current_time + p_slot_duration AS TIME);
        END IF;
        
        v_current_time := v_current_time + p_slot_duration;
    END LOOP;
END;
$$ LANGUAGE plpgsql;

