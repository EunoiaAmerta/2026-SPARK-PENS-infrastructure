    r."Building",
    r."Floor"
FROM "Bookings" b
INNER JOIN "Rooms" r ON b."RoomId" = r."Id"
WHERE b."IsDeleted" = FALSE
ORDER BY b."CreatedDate" DESC;

-- View for room availability summary
CREATE OR REPLACE VIEW v_room_availability AS
SELECT 
    r."Id" AS room_id,
    r."Name" AS room_name,
    r."Building",
    r."Floor",
    r."Capacity",
    r."IsAvailable",
    COUNT(b."Id") FILTER (WHERE b."Status" = 'Pending') AS pending_bookings,
    COUNT(b."Id") FILTER (WHERE b."Status" = 'Approved') AS approved_bookings,
    COUNT(b."Id") FILTER (WHERE b."Status" = 'Rejected') AS rejected_bookings
FROM "Rooms" r
LEFT JOIN "Bookings" b ON r."Id" = b."RoomId" AND b."IsDeleted" = FALSE
WHERE r."IsDeleted" = FALSE
GROUP BY r."Id", r."Name", r."Building", r."Floor", r."Capacity", r."IsAvailable";

